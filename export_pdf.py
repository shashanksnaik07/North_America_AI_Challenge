"""
export_pdf.py - prints a student's IEP in the layout of the Alabama IEP form
(ALSDE, Feb. 2019). Every page is marked DRAFT, because it is produced by an
app and still needs the IEP team's review and signatures.
"""

import io
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.enums import TA_CENTER
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import ParagraphStyle
from reportlab.lib.units import inch
from reportlab.pdfgen import canvas
from reportlab.platypus import (KeepTogether, PageBreak, Paragraph, SimpleDocTemplate,
                                Spacer, Table, TableStyle)

import iep_schema as S

FONT, BOLD = "Times-Roman", "Times-Bold"
W = 7.5 * inch  # usable width
st_body = ParagraphStyle("body", fontName=FONT, fontSize=9.5, leading=11.5)
st_bold = ParagraphStyle("bold", parent=st_body, fontName=BOLD)
st_small = ParagraphStyle("small", parent=st_body, fontSize=8.5, leading=10)
st_head = ParagraphStyle("head", parent=st_bold, fontSize=10.5, alignment=TA_CENTER, leading=13)
st_left_head = ParagraphStyle("lhead", parent=st_bold, fontSize=10.5, leading=13)


def P(text, style=st_body):
    return Paragraph(escape(str(text or "")).replace("\n", "<br/>"), style)


def B(text, style=st_bold):
    return Paragraph(text, style)  # trusted markup (labels written in this file)


def box(text) -> str:
    return "[X]" if text else "[&nbsp;&nbsp;]"


def yn(value) -> str:
    return f"{box(value is True)} YES&nbsp;&nbsp;&nbsp;&nbsp;{box(value is False)} NO"


GRID = [("GRID", (0, 0), (-1, -1), 0.6, colors.black),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("TOPPADDING", (0, 0), (-1, -1), 2), ("BOTTOMPADDING", (0, 0), (-1, -1), 3)]


def table(rows, widths, extra=(), min_heights=None):
    t = Table(rows, colWidths=widths, rowHeights=min_heights)
    t.setStyle(TableStyle(GRID + list(extra)))
    return t


def labeled_block(label: str, help_text: str, value: str):
    """A form box: bold label, small instructions, then the filled-in text."""
    return [[B(label)], [P(help_text, st_small)], [P(value or " ")]]


# ---------------------------------------------------------------------------
# Page numbers ("Page X of Y") and the header on every page
# ---------------------------------------------------------------------------
class NumberedCanvas(canvas.Canvas):
    def __init__(self, *args, iep=None, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved = []
        self.iep = iep

    def showPage(self):
        self._saved.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        total = len(self._saved)
        for state in self._saved:
            self.__dict__.update(state)
            self._decorate(total)
            super().showPage()
        super().save()

    def _decorate(self, total):
        page = self._pageNumber
        self.setFont(BOLD, 13)
        self.drawCentredString(4.25 * inch, 10.55 * inch,
                               " ".join("INDIVIDUALIZED") + "     " + " ".join("EDUCATION") +
                               "     " + " ".join("PROGRAM"))
        if page > 1:
            self.setFont(BOLD, 9.5)
            self.drawString(0.5 * inch, 10.25 * inch, "STUDENT'S NAME:")
            self.drawString(5.6 * inch, 10.25 * inch, "DOB:")
            self.setFont(FONT, 9.5)
            self.drawString(1.75 * inch, 10.25 * inch, self.iep["student_name"])
            self.drawString(6.0 * inch, 10.25 * inch, self.iep["dob"])
            self.line(1.7 * inch, 10.22 * inch, 5.4 * inch, 10.22 * inch)
            self.line(5.95 * inch, 10.22 * inch, 8.0 * inch, 10.22 * inch)
        self.setFont(FONT, 8)
        self.drawString(0.5 * inch, 0.45 * inch, f"Page {page} of {total}")
        self.drawRightString(8.0 * inch, 0.45 * inch,
                             "Based on ALSDE IEP form (Feb. 2019)  ·  DRAFT generated by IEP Bridge")
        self.setFillColor(colors.Color(0.85, 0.1, 0.1, alpha=0.08))
        self.setFont(BOLD, 90)
        self.saveState()
        self.translate(4.25 * inch, 5.2 * inch)
        self.rotate(35)
        self.drawCentredString(0, 0, "DRAFT")
        self.restoreState()
        self.setFillColor(colors.black)


