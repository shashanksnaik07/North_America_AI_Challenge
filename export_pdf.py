def page_profile(iep):
    out = [table(
        [[B("STUDENT'S NAME"), P(iep["student_name"]), "", "", "", ""],
         [B("DOB"), P(iep["dob"]), B("SCHOOL YEAR"), P(iep["school_year"]), B("GRADE"), P(iep["grade"])],
         [B("IEP INITIATION/DURATION DATES"), "", B("FROM"), P(iep["iep_from"]), B("TO"), P(iep["iep_to"])]],
        [1.3 * inch, 1.5 * inch, 1.05 * inch, 1.55 * inch, 0.75 * inch, 1.35 * inch],
        extra=[("SPAN", (1, 0), (5, 0)), ("SPAN", (0, 2), (1, 2))])]
    out.append(table([[B("This IEP will be implemented during the regular school term unless noted "
                         "in extended school year services.")]], [W]))
    rows = [[B("STUDENT PROFILE – WILL INCLUDE GENERAL STATEMENTS REGARDING:", st_head)]]
    helps = {
        "strengths": "Include information regarding the student's strengths in academic and functional areas.",
        "parent_concerns": "Include all information regarding the parental concerns for enhancing the education of their child.",
        "preferences_interests": "Information obtained from parent, teacher(s), and the student regarding preferences and interests, including transition information.",
        "evaluation_results": "Include all information concerning evaluation results, written in meaningful terms.",
        "needs": "How the student's disability affects his/her involvement and progress in the general education curriculum.",
        "other": "Any information pertinent to the development of the IEP not included elsewhere on the Student Profile page.",
        "ei_transition_justification": "Only completed if the child is not being served under IDEA on the child's third birthday.",
    }
    for k, label in S.PROFILE_FIELDS:
        rows += labeled_block(f"{label} –", helps[k], iep["profile"][k])
    style = []
    for i in range(1, len(rows), 3):  # no inner lines inside one form box
        style += [("LINEBELOW", (0, i), (0, i + 1), 0, colors.white)]
    out.append(table(rows, [W], extra=style))
    return out


def page_factors(iep):
    rows = [[B("SPECIAL INSTRUCTIONAL FACTORS", st_head), "", ""],
            [B('Items checked "YES" will be addressed in this IEP:'), B("YES"), B("NO")]]
    for k, q in S.SPECIAL_FACTORS:
        v = iep["special_factors"][k]
        rows.append([P("• " + q), B(box(v is True)), B(box(v is False))])
    out = [table(rows, [6.3 * inch, 0.6 * inch, 0.6 * inch], extra=[("SPAN", (0, 0), (2, 0))]), Spacer(1, 6)]

    t = iep["transportation"]
    modes = "&nbsp;&nbsp;".join(f"{box(t['mode'] == m)} {m}" for m in S.TRANSPORT_MODES)
    needs = "<br/>".join(f"{box(n in t['needs'])} {n}" for n in S.TRANSPORT_NEEDS)
    rows = [[B("TRANSPORTATION", st_head)],
            [B(f"Student's mode of transportation: {modes}"
               + (f": {escape(t['mode_other'])}" if t["mode_other"] else ""), st_body)],
            [B(f"Does the student require transportation as a related service? {yn(t['related_service'])}", st_body)],
            [B(f"{box(t['transport_rep_involved'])} If Yes, a representative from the transportation department "
               f"was included in the meeting or in discussions prior to the meeting.", st_small)],
            [B(f"Check any transportation needs:<br/>{needs}", st_body)],
            [P(f"Details: {t['needs_details']}" if t["needs_details"] else " ")]]
    out += [table(rows, [W]), Spacer(1, 6)]

    n = iep["nonacademic"]
    opts = "<br/>".join(f"{box(n['participation'] == o)} {o}" for o in S.NONACADEMIC_OPTIONS)
    rows = [[B("NONACADEMIC and EXTRACURRICULAR ACTIVITIES", st_head)],
            [P("Will the student have the opportunity to participate in nonacademic/extracurricular "
               "activities with his/her nondisabled peers?")],
            [B(opts, st_body)],
            [P(f"Describe / explanation: {n['description']}" if n["description"] else " ")]]
    out += [table(rows, [W]), Spacer(1, 6)]
    rows = [[B("METHOD/FREQUENCY FOR REPORTING PROGRESS OF ATTAINING GOALS TO PARENTS", st_head)],
            [P(f"Annual Goal Progress reports will be sent to parents each time report cards are issued "
               f"(every {iep['progress_report_weeks'] or '____'} weeks).")]]
    out.append(table(rows, [W]))
    return out


def page_transition(iep):
    tr = iep["transition"]
    out = [P("Transition: Beginning not later than the first IEP to be in effect when the student is 16, or "
             "earlier if appropriate, and updated annually thereafter. For all students entering 9th grade "
             "regardless of their age, transition must be addressed.", st_small), Spacer(1, 4)]
    rows = [[B(f"{box(tr['student_invited_date'])} This student was invited to the IEP Team meeting on "
               f"{escape(tr['student_invited_date'] or '______')} via {escape(tr['student_invited_via'] or '______')}.", st_body)],
            [B(f"{box(tr['agencies_invited'])} After prior consent of the parent or student (Age 19) was obtained, "
               f"other agency representatives were invited to the IEP Team meeting.", st_body)],
            [B(f"{box(tr['addressed_on_goal_page'])} Transition services based on the student's strengths, "
               f"preferences, and interests are addressed on the transition goal page in this IEP.", st_body)]]
    out += [table(rows, [W]), Spacer(1, 4)]
    assess = "&nbsp;&nbsp;&nbsp;".join(f"{box(a in tr['assessments'])} {a}" for a in S.TRANSITION_ASSESSMENTS)
    rows = [[B("Age-appropriate Transition Assessments:")], [B(assess, st_body)]]
    for k, label in S.POSTSECONDARY_AREAS:
        ps = tr["postsecondary"][k]
        rows.append([B(label)])
        for a in (ps["assessments"] + [{"name": "", "date": ""}] * 2)[:2]:
            rows.append([P(f"Assessment: {a['name']}        Date: {a['date']}")])
        rows.append([P(f"Long-Term Goal: {ps['long_term_goal']}")])
    out += [table(rows, [W]), Spacer(1, 4)]
    path = "<br/>".join(f"{box(tr['pathway'] == p)} {p}" for p in S.PATHWAYS)
    rows = [[B(f"{box(tr['middle_school_course'])} This student is in a middle school course of study that "
               f"will help prepare him/her for transition.", st_body)],
            [B(f"Anticipated Date of Exit: Month: {escape(tr['exit_month'])}   Year: {escape(tr['exit_year'])}", st_body)],
            [B(f"Selected Pathway to the Alabama High School Diploma:<br/>{path}", st_body)]]
    out += [table(rows, [W]), Spacer(1, 4)]
    credit_rows = [[B("Program Credits to be Earned (grades 9-12)"), B("ENGLISH"), B("MATH"), B("SCIENCE"),
                    B("SOCIAL STUDIES")]]
    for p in S.PATHWAYS:
        c = tr["credits"][p]
        credit_rows.append([P(p), P(c["english"]), P(c["math"]), P(c["science"]), P(c["social_studies"])])
    credit_rows.append([P(f"Elective(s): {tr['electives']}"), "", "", "", ""])
    out.append(table(credit_rows, [3.5 * inch, inch, inch, inch, inch], extra=[("SPAN", (0, 4), (4, 4))]))
    return out


def page_transition_goals(iep):
    tg = iep["transition_goals"]
    rows = [[B("ANNUAL TRANSITION GOAL(S)", st_head)],
            [B("PRESENT LEVEL OF ACADEMIC ACHIEVEMENT AND FUNCTIONAL PERFORMANCE:")],
            [P(tg["present_level"] or " ")],
            [B("MEASURABLE ANNUAL POSTSECONDARY TRANSITION GOALS:")]]
    for k, label in S.POSTSECONDARY_AREAS:
        g = tg[k]
        acts = "<br/>".join(f"{i}. {escape(a)}" for i, a in enumerate(g["activities"] or ["", ""], 1))
        rows += [[B(f"{label}: {escape(g['goal'])}<br/>Date of Completion/Mastery: {escape(g['mastery_date'])}", st_body)],
                 [B(f"*Transition Service(s): {escape(g['services'])}", st_body)],
                 [B(f"Transition Activities:<br/>{acts}", st_body)],
                 [B(f"Person(s)/Agency Involved: {escape(g['people'])}", st_body)]]
    out = [table(rows, [W])]
    out.append(P("*Transition Services: Vocational Evaluations (VE), Community Experiences (CE), Personal "
                 "Management (PM), Transportation (T), Employment Development (ED), Medical (M), Postsecondary "
                 "Education (PE), Living Arrangements (LA), Linkages to Agencies (LTA), Advocacy/Guardianship (AG), "
                 "Financial Management (FM), Functional Vocational Evaluation (FVE).", st_small))
    return out


def page_goal(g):
    ev = g["evaluation"]
    checks = "&nbsp;&nbsp;&nbsp;".join(f"{box(e in ev)} {e}" for e in S.EVALUATION_TYPES)
    if g["evaluation_other"]:
        checks += f": {escape(g['evaluation_other'])}"
    bms = (g["benchmarks"] + [{"text": "", "date": ""}] * 4)[:4]
    rows = [[B(f"AREA: {escape(g['area'])}", st_body), ""],
            [B("PRESENT LEVEL OF ACADEMIC ACHIEVEMENT AND FUNCTIONAL PERFORMANCE:"), ""],
            [P("State how the student's disability affects his/her involvement and progress in the general "
               "education curriculum for this particular area of instruction.", st_small), ""],
            [P(g["present_level"] or " "), ""],
            [B("MEASURABLE ANNUAL GOAL related to meeting the student's needs:"), ""],
            [P(g["goal"] or " "), ""],
            [B(f"DATE OF MASTERY: {escape(g['mastery_date'])}", st_body), ""],
            [B("TYPE(S) OF EVALUATION FOR ANNUAL GOAL:"), ""],
            [B(checks, st_body), ""],
            [B("BENCHMARKS:"), ""]]
    rows += [[P(f"{i}. {b['text']}"), P(f"Date of Mastery: {b['date']}")] for i, b in enumerate(bms, 1)]
    spans = [("SPAN", (0, r), (1, r)) for r in range(10)]
    return [table(rows, [5.6 * inch, 1.9 * inch], extra=spans)]


def page_services(iep):
    out = [B("SPECIAL EDUCATION AND RELATED SERVICE(S): (Special Education, Supplementary Aids and Services, "
             "Program Modifications, Accommodations Needed for Assessments, Related Services, Assistive "
             "Technology, and Support for Personnel.)", st_body), Spacer(1, 4)]
    widths = [2.4 * inch, 1.15 * inch, 0.95 * inch, 1.5 * inch, 1.5 * inch]
    head = [B("Service(s)"), B("Anticipated Frequency of Service(s)", st_small), B("Amount of time", st_small),
            B("Beginning/Ending Duration Dates", st_small), B("Location of Service(s)", st_small)]
    for k, label in S.SERVICE_CATEGORIES:
        cat = iep["services"][k]
        title = f"<b>{label}</b>"
        if k != "special_education":
            title += f"&nbsp;&nbsp;&nbsp;&nbsp;{box(cat['needed'])} Needed&nbsp;&nbsp;{box(not cat['needed'])} Not Needed"
        rows = [head]
        for r in cat["rows"] or [S.empty_service(), S.empty_service()]:
            rows.append([P(r["service"]), P(r["frequency"]), P(r["amount"]),
                         P(f"{r['begin']} to {r['end']}" if (r["begin"] or r["end"]) else "to"),
                         P(r["location"])])
        out.append(KeepTogether([Paragraph(title, st_body), Spacer(1, 2), table(rows, widths), Spacer(1, 6)]))
    return out


def page_final(iep):
    lre, c = iep["lre"], iep["copies"]
    age = (f"{box(lre['age_group'] == '6-21')} 6-21 YEARS OF AGE&nbsp;&nbsp;&nbsp;&nbsp;"
           f"{box(lre['age_group'] == '3-5')} 3-5 YEARS OF AGE")
    rows = [[B("TRANSFER OF RIGHTS", st_head)],
            [P("(Beginning not later than the IEP that will be in effect when the student reaches 18 years of age.) "
               f"Date student was informed that the rights under the IDEA will transfer to him/her at the age of 19: "
               f"{iep['transfer_of_rights_date']}")],
            [B("EXTENDED SCHOOL YEAR SERVICES (ESY)", st_head)],
            [B(f"The IEP Team has considered the need for extended school year services. {yn(iep['esy_considered'])}", st_body)],
            [B("LEAST RESTRICTIVE ENVIRONMENT", st_head)],
            [B("Does this student attend the school he/she would attend if nondisabled? "
               f"{yn(lre['attends_home_school'])}", st_body)],
            [P(f"If no, explain: {lre['home_school_explain']}")],
            [B("Does this student receive all special education services with nondisabled peers? "
               f"{yn(lre['all_with_nondisabled'])}", st_body)],
            [P(f"If no, explain: {lre['nondisabled_explain']}")],
            [B(age, st_body)],
            [P(f"Least Restrictive Environment: {lre['setting']}")]]
    out = [table(rows, [W]), Spacer(1, 6)]
    rows = [[B("COPY OF IEP", st_head), B("COPY OF SPECIAL EDUCATION RIGHTS", st_head)],
            [B(f"Was a copy of the IEP given to parent/student (age 19) at the IEP Team meeting? "
               f"{yn(c['iep_given'])}<br/>If no, date sent: {escape(c['iep_sent_date'])}", st_body),
             B(f"Was a copy of the Special Education Rights given to parent/student (age 19) at the IEP Team "
               f"meeting? {yn(c['rights_given'])}<br/>If no, date sent: {escape(c['rights_sent_date'])}", st_body)],
            [P(f"Date copy of amended IEP provided/sent to parent/student (age 19): {c['amended_sent_date']}"), ""]]
    out += [table(rows, [W / 2, W / 2], extra=[("SPAN", (0, 2), (1, 2))]), Spacer(1, 6)]
    rows = [[B("THE FOLLOWING PEOPLE ATTENDED AND PARTICIPATED IN THE MEETING TO DEVELOP THIS IEP.", st_head), "", ""],
            [B("Position"), B("Signature"), B("Date")]]
    rows += [[P(p["position"], st_small), P(p["name"]), P(p["date"])] for p in iep["participants"]]
    out += [table(rows, [3.3 * inch, 2.9 * inch, 1.3 * inch], extra=[("SPAN", (0, 0), (2, 0))]), Spacer(1, 6)]
    rows = [[B("INFORMATION FROM PEOPLE NOT IN ATTENDANCE", st_head), "", ""],
            [B("Position"), B("Name"), B("Date")]]
    rows += [[P(p["position"]), P(p["name"]), P(p["date"])] for p in iep["not_in_attendance"]] or [["", "", ""]]
    rows += [["", "", ""]] * (4 - len(rows)) if len(rows) < 4 else []
    out.append(table(rows, [3.3 * inch, 2.9 * inch, 1.3 * inch], extra=[("SPAN", (0, 0), (2, 0))]))
    return out


def build_pdf(iep: dict) -> bytes:
    iep = S.normalize(iep)
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=letter, leftMargin=0.5 * inch, rightMargin=0.5 * inch,
                            topMargin=0.95 * inch, bottomMargin=0.7 * inch,
                            title=f"IEP - {iep['student_name']}", author="IEP Bridge (draft)")
    story = page_profile(iep) + [PageBreak()] + page_factors(iep)
    if iep["transition"]["applicable"]:
        story += [PageBreak()] + page_transition(iep) + [PageBreak()] + page_transition_goals(iep)
    for g in iep["goals"] or [S.empty_goal()]:
        story += [PageBreak()] + page_goal(g)
    story += [PageBreak()] + page_services(iep) + [PageBreak()] + page_final(iep)
    doc.build(story, canvasmaker=lambda *a, **k: NumberedCanvas(*a, iep=iep, **k))
    return buf.getvalue()
